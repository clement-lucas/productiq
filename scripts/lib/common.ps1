# Shared helpers for ProductIQ setup scripts (PowerShell 7+). Dot-source:  . "$PSScriptRoot/lib/common.ps1"
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$script:RepoRoot   = (Resolve-Path (Join-Path $PSScriptRoot '..' '..')).Path
if (-not (Test-Path (Join-Path $script:RepoRoot 'infra'))) { $script:RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path }
$script:ConfigPath  = Join-Path $script:RepoRoot 'config/environment.json'
$script:OutputsPath = Join-Path $script:RepoRoot 'config/outputs.json'
$script:EnvPath     = Join-Path $script:RepoRoot '.env'

function Write-Step([string]$Message) { Write-Host "`n==> $Message" -ForegroundColor Cyan }
function Write-Ok([string]$Message)   { Write-Host "    [ok] $Message" -ForegroundColor Green }
function Write-Warn2([string]$Message){ Write-Host "    [!] $Message" -ForegroundColor Yellow }

function Get-RepoRoot { $script:RepoRoot }

function Get-ProductIQConfig {
    if (-not (Test-Path $script:ConfigPath)) {
        throw "config/environment.json not found. Copy config/environment.sample.json to config/environment.json and fill it in."
    }
    Get-Content $script:ConfigPath -Raw | ConvertFrom-Json
}

function Get-ProductIQOutputs {
    if (Test-Path $script:OutputsPath) { return (Get-Content $script:OutputsPath -Raw | ConvertFrom-Json -AsHashtable) }
    return @{}
}

# Merge key/values into config/outputs.json and regenerate .env (KEY=VALUE, consumed by Python scripts and the app)
function Set-ProductIQOutputs([hashtable]$Values) {
    $current = Get-ProductIQOutputs
    foreach ($k in $Values.Keys) { if ($null -ne $Values[$k]) { $current[$k] = [string]$Values[$k] } }
    ($current | ConvertTo-Json -Depth 5) | Set-Content -Path $script:OutputsPath -Encoding utf8
    $lines = @('# Generated by scripts/*.ps1 – do not commit. Source of truth: config/outputs.json')
    foreach ($k in ($current.Keys | Sort-Object)) { $lines += "$k=$($current[$k])" }
    $lines | Set-Content -Path $script:EnvPath -Encoding utf8
}

function Assert-Command([string]$Name, [string]$Hint) {
    if (-not (Get-Command $Name -ErrorAction SilentlyContinue)) { throw "'$Name' not found. $Hint" }
}

function Get-Python {
    foreach ($c in @('python3', 'python', 'py')) { if (Get-Command $c -ErrorAction SilentlyContinue) { return $c } }
    throw 'Python 3.11+ not found.'
}

# Run a Python script from the repo virtual environment (created by 00-check-prereqs.ps1)
function Invoke-RepoPython([string]$ScriptPath, [string[]]$Arguments = @()) {
    $venvPy = if ($IsWindows) { Join-Path $script:RepoRoot '.venv/Scripts/python.exe' } else { Join-Path $script:RepoRoot '.venv/bin/python' }
    $py = if (Test-Path $venvPy) { $venvPy } else { Get-Python }
    & $py (Join-Path $script:RepoRoot $ScriptPath) @Arguments
    if ($LASTEXITCODE -ne 0) { throw "Python script failed: $ScriptPath (exit $LASTEXITCODE)" }
}

function Set-AzContextFromConfig($cfg) {
    $acct = az account show 2>$null | ConvertFrom-Json
    if (-not $acct -or $acct.tenantId -ne $cfg.tenantId) {
        throw "Azure CLI is not signed in to tenant $($cfg.tenantId). Run scripts/01-login.ps1 first."
    }
    az account set --subscription $cfg.subscriptionId | Out-Null
}
