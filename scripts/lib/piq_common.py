"""Shared helpers for the ProductIQ setup scripts: .env loading, Entra tokens, REST calls with long-running-operation polling."""
from __future__ import annotations

import json
import os
import sys
import time
from pathlib import Path
from typing import Any

import requests

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUTS_PATH = REPO_ROOT / "config" / "outputs.json"
ENV_PATH = REPO_ROOT / ".env"

SCOPE_ARM = "https://management.azure.com/.default"
SCOPE_FABRIC = "https://api.fabric.microsoft.com/.default"
SCOPE_STORAGE = "https://storage.azure.com/.default"
SCOPE_SEARCH = "https://search.azure.com/.default"
SCOPE_FOUNDRY = "https://ai.azure.com/.default"


def log(msg: str) -> None:
    print(f"    {msg}", flush=True)


def step(msg: str) -> None:
    print(f"\n==> {msg}", flush=True)


def load_outputs() -> dict[str, str]:
    """Read config/outputs.json (written by the PowerShell scripts) and overlay environment variables."""
    data: dict[str, str] = {}
    if OUTPUTS_PATH.exists():
        data.update(json.loads(OUTPUTS_PATH.read_text(encoding="utf-8")))
    for k, v in os.environ.items():
        if k.isupper() and k not in data:
            data[k] = v
    return data


def save_outputs(values: dict[str, Any]) -> None:
    """Merge values into config/outputs.json and regenerate .env."""
    data = {}
    if OUTPUTS_PATH.exists():
        data = json.loads(OUTPUTS_PATH.read_text(encoding="utf-8"))
    data.update({k: str(v) for k, v in values.items() if v is not None})
    OUTPUTS_PATH.write_text(json.dumps(data, indent=2), encoding="utf-8")
    lines = ["# Generated by scripts – do not commit. Source of truth: config/outputs.json"]
    lines += [f"{k}={data[k]}" for k in sorted(data)]
    ENV_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def require(outputs: dict[str, str], *keys: str) -> list[str]:
    missing = [k for k in keys if not outputs.get(k)]
    if missing:
        sys.exit(f"Missing values in config/outputs.json: {', '.join(missing)}. Run the earlier setup scripts first.")
    return [outputs[k] for k in keys]


_credential = None


def credential():
    """Azure CLI credential (developer sign-in via scripts/01-login.ps1)."""
    global _credential
    if _credential is None:
        from azure.identity import AzureCliCredential
        _credential = AzureCliCredential(process_timeout=60)
    return _credential


def token(scope: str) -> str:
    return credential().get_token(scope).token


class Rest:
    """Tiny REST client with bearer auth, retries on 429/5xx and Fabric/ARM long-running-operation polling."""

    def __init__(self, base_url: str, scope: str):
        self.base_url = base_url.rstrip("/")
        self.scope = scope

    def _headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {token(self.scope)}", "Content-Type": "application/json"}

    def request(self, method: str, path: str, body: Any | None = None, ok=(200, 201, 202, 204), lro: bool = True,
                params: dict | None = None) -> requests.Response:
        url = path if path.startswith("http") else f"{self.base_url}{path}"
        for attempt in range(6):
            r = requests.request(method, url, headers=self._headers(), params=params,
                                 data=None if body is None else json.dumps(body), timeout=120)
            if r.status_code in (429, 500, 502, 503, 504):
                wait = int(r.headers.get("Retry-After", 5 * (attempt + 1)))
                log(f"{r.status_code} from {method} {url} – retrying in {wait}s")
                time.sleep(wait)
                continue
            break
        if r.status_code not in ok:
            raise RuntimeError(f"{method} {url} failed: {r.status_code} {r.text[:800]}")
        if lro and r.status_code == 202 and r.headers.get("Location"):
            return self.wait_operation(r)
        return r

    def wait_operation(self, r: requests.Response, timeout_s: int = 1800) -> requests.Response:
        """Poll a Fabric/ARM 202 Accepted operation until it finishes; returns the result response if any."""
        location = r.headers["Location"]
        deadline = time.time() + timeout_s
        while time.time() < deadline:
            time.sleep(int(r.headers.get("Retry-After", 5)))
            r = requests.get(location, headers=self._headers(), timeout=60)
            if r.status_code == 200 and r.content:
                body = r.json()
                status = str(body.get("status", "")).lower()
                if status in ("succeeded", "completed"):
                    res = requests.get(location.rstrip("/") + "/result", headers=self._headers(), timeout=60)
                    return res if res.status_code == 200 else r
                if status in ("failed", "cancelled", "canceled", "deduped"):
                    raise RuntimeError(f"Operation failed: {json.dumps(body)[:800]}")
                if not status:  # some APIs return the created resource directly
                    return r
            elif r.status_code in (201, 204):
                return r
            elif r.status_code != 202:
                raise RuntimeError(f"Polling {location} failed: {r.status_code} {r.text[:500]}")
        raise TimeoutError(f"Timed out waiting for {location}")

    def get(self, path: str, **kw) -> Any:
        r = self.request("GET", path, **kw)
        return r.json() if r.content else {}

    def post(self, path: str, body: Any | None = None, **kw) -> requests.Response:
        return self.request("POST", path, body, **kw)

    def put(self, path: str, body: Any | None = None, **kw) -> requests.Response:
        return self.request("PUT", path, body, **kw)
